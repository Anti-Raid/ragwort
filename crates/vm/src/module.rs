//! Runtime representation of modules: defines the module instances storing top-level variables, host functions implemented in Rust, and host object reference wrappers.
//!
//! A host function is defined using [`HostDef`]. The VM dispatch loop invokes it for [`crate::Op::CallHost`] operations via the host table of the calling module, passing arguments and a [`HostContext`]. Host functions are invoked from Scheme through native wrapper procedures using `%call-host`, which explicitly pass any required VM state (such as coroutine references or continuation marks) or host data (encapsulated in [`ExternalRef`]).

use std::any::{Any, TypeId};
use std::fmt;

use ragwort_types::gc::{Frame, Gc, Mutation, OutOfMemory, Value};
use ragwort_types::vector::Vectors;

use crate::objects::{ExternalRef, ExternalRefFields, Module, ModuleFields};
use crate::{Fault, Fuel};

/// Function signature for a host function callable from bytecode: receives a mutable [`HostContext`] and [`HostArgs`], returning a [`Reply`] or a [`Fault`].
pub type HostFn = for<'s, 'gc> fn(&mut HostContext<'s, 'gc>, HostArgs<'s, 'gc>) -> Result<Reply<'gc>, Fault>;

/// Host function metadata registered in a module's static host table and shared across virtual machine instances. Constructed using the [`host!`](crate::host!) macro.
#[derive(Clone, Copy, Debug)]
pub struct HostDef {
    pub name: &'static str,
    /// Canonical module path to the host function definition generated by [`host!`](crate::host!). Used to disambiguate and resolve host functions during heap image serialization and deserialization.
    pub path: &'static str,
    /// Encoded expected argument arity, matching [`crate::objects::Bytecode`] encoding conventions.
    pub arity: i64,
    pub purity: Purity,
    pub function: HostFn,
    /// Unique [`TypeId`] of the Rust function item, distinguishing it from other host functions.
    pub id: TypeId,
}

/// Constructs a [`HostDef`] definition: `host!(name, arity, purity, function)`, capturing the full path and [`TypeId`] of the target Rust function.
#[macro_export]
macro_rules! host {
    ($name:expr, $arity:expr, $purity:expr, $function:path $(,)?) => {
        $crate::HostDef {
            name: $name,
            path: concat!(module_path!(), "::", stringify!($function)),
            arity: $arity,
            purity: $purity,
            function: $function,
            id: $crate::HostDef::id_of(&$function),
        }
    };
}

impl HostDef {
    /// Returns the unique [`TypeId`] corresponding to the concrete type of `function`.
    pub const fn id_of<F: 'static>(_function: &F) -> TypeId {
        TypeId::of::<F>()
    }

    /// Returns `true` if this host function accepts `n` arguments.
    #[inline]
    pub fn takes(&self, n: usize) -> bool {
        takes(self.arity, n)
    }
}

/// Compares two [`HostDef`] definitions for structural equality based on name, arity, purity, and function type identity.
impl PartialEq for HostDef {
    fn eq(&self, other: &Self) -> bool {
        (self.name, self.arity, self.purity, self.id) == (other.name, other.arity, other.purity, other.id)
    }
}

impl Eq for HostDef {}

/// Declares purity and side-effect guarantees of a host function for compiler optimization. Functions that perform side effects or return non-value replies must be marked [`Purity::Impure`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Purity {
    /// May perform arbitrary side effects; calls must be preserved in original program order.
    Impure,
    /// Has no observable side effects other than reading arguments and returning a value or faulting.
    Pure,
    /// Strictly pure and guaranteed never to fault; calls may be safely eliminated by the compiler if their results are unused.
    Discardable,
}

impl Purity {
    /// Returns `true` if calls to this function can be safely reordered relative to other pure operations.
    pub const fn is_reorderable(self) -> bool {
        !matches!(self, Purity::Impure)
    }
}

/// The result returned by a host function invocation to the virtual machine.
pub enum Reply<'gc> {
    Value(Value<'gc>),
    /// Invokes the specified procedure with arguments provided in a Scheme list as a tail call replacing the host call.
    Call(Value<'gc>, Value<'gc>),
    /// Raises an exception condition with the specified value, equivalent to calling `raise`.
    Raise(Value<'gc>),
    /// Suspends VM execution with [`crate::Outcome::Deferred`] holding the given payload, until resumed via [`crate::Machine::reply`] or [`crate::Machine::raise`].
    Defer(Box<dyn Any>),
}

/// Provides host functions with execution context: access to the garbage collector mutation context and VM fuel management.
pub struct HostContext<'s, 'gc> {
    pub(crate) mc: &'s Mutation<'gc>,
    pub(crate) fuel: &'s mut Fuel,
}

impl<'s, 'gc> HostContext<'s, 'gc> {
    #[inline]
    pub fn mc(&self) -> &'s Mutation<'gc> {
        self.mc
    }

    /// Deducts `units` of execution fuel for computational work performed by the host call, returning [`Fault::OutOfFuel`] if remaining fuel is exceeded.
    #[inline]
    pub fn charge(&mut self, units: u64) -> Result<(), Fault> {
        self.fuel.spend(units)
    }
}

/// Accessor for host function arguments located directly within the caller's execution frame registers.
#[derive(Clone, Copy)]
pub struct HostArgs<'s, 'gc> {
    frame: Frame<'s, 'gc>,
    base: u8,
    len: u8,
}

impl<'s, 'gc> HostArgs<'s, 'gc> {
    #[inline]
    pub(crate) fn registers(frame: Frame<'s, 'gc>, base: u8, len: u8) -> Self {
        HostArgs { frame, base, len }
    }

    #[inline]
    pub fn len(self) -> usize {
        usize::from(self.len)
    }

    #[inline]
    pub fn is_empty(self) -> bool {
        self.len == 0
    }

    #[inline]
    pub fn get(self, i: usize) -> Option<Value<'gc>> {
        let i = u8::try_from(i).ok().filter(|&i| i < self.len)?;
        Some(self.frame.get(self.base + i))
    }

    #[inline]
    pub fn iter(self) -> impl ExactSizeIterator<Item = Value<'gc>> + use<'s, 'gc> {
        (0..self.len()).map(move |i| self.get(i).expect("an argument below the count"))
    }
}

impl fmt::Debug for HostArgs<'_, '_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_list().entries(self.iter()).finish()
    }
}

/// Opaque host data payload associated with a suspended [`Reply::Defer`] operation, returned to the host via [`crate::Outcome::Deferred`].
pub struct Deferred(Box<Box<dyn Any>>);

impl Deferred {
    pub(crate) fn new(data: Box<dyn Any>) -> Self {
        Deferred(Box::new(data))
    }

    pub fn into_inner(self) -> Box<dyn Any> {
        *self.0
    }
}

impl fmt::Debug for Deferred {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("Deferred")
    }
}

/// Always returns `true`, treating all deferred payloads as equivalent from the perspective of VM state comparison.
impl PartialEq for Deferred {
    fn eq(&self, _: &Self) -> bool {
        true
    }
}

impl Eq for Deferred {}

/// Creates a new [`Module`] named `name` with uninitialized top-level variable slots corresponding to `names`, and registers the host functions (`hosts`) referenced by its native or inlined bytecode.
pub fn new<'gc>(mc: &Mutation<'gc>, name: Value<'gc>, names: &[Value<'gc>], hosts: impl IntoIterator<Item = &'static HostDef>) -> Result<Gc<'gc, Module>, OutOfMemory> {
    let vector = Vectors::new(mc).immutable_from_slice(names)?.value(mc);
    let interface: Box<dyn Any> = Box::new(());
    let hosts: Box<[&'static HostDef]> = hosts.into_iter().collect();
    Module::new(mc, name, vector, mc.frozen(hosts)?, mc.frozen(interface)?, names.len(), Value::UNDEFINED)
}

/// Downcasts and returns a reference to the compiler export interface stored in `module` if it matches type `T`.
pub fn interface<'gc, T: Any>(mc: &Mutation<'gc>, module: Gc<'gc, Module>) -> Option<&'gc T> {
    module.interface(mc)?.downcast_ref()
}

/// Stores compiler export metadata `interface` into `module`.
pub fn set_interface<'gc, T: Any>(mc: &Mutation<'gc>, module: Gc<'gc, Module>, interface: T) -> Result<(), OutOfMemory> {
    let interface: Box<dyn Any> = Box::new(interface);
    module.set_interface(mc, mc.frozen(interface)?);
    Ok(())
}

/// Allocates an [`ExternalRef`] wrapping host payload `data`, charging `bytes` of external memory to the garbage collector heap, and associating it with GC-traced value `held`.
pub fn external<'gc, T: Any>(mc: &Mutation<'gc>, data: T, bytes: usize, held: Value<'gc>) -> Result<Gc<'gc, ExternalRef>, OutOfMemory> {
    let data: Box<dyn Any> = Box::new(data);
    ExternalRef::new(mc, held, mc.frozen_owning(data, bytes)?)
}

/// Downcasts and returns a reference to the host payload stored in `external` if it is an [`ExternalRef`] wrapping type `T`.
pub fn external_data<'gc, T: Any>(mc: &Mutation<'gc>, external: Value<'gc>) -> Option<&'gc T> {
    external.downcast::<ExternalRef>(mc)?.data(mc)?.downcast_ref()
}

/// Returns `true` if an encoded arity integer (formatted as in [`Bytecode`]) accepts `n` arguments.
#[inline]
pub(crate) fn takes(arity: i64, n: usize) -> bool {
    let n = n as i64;
    if arity == n {
        true
    } else if arity < 0 {
        n >= -(arity + 1)
    } else {
        crate::frame::Shape::of(arity).takes(n as u64)
    }
}
