//! Struct types and instances created by the `struct` syntactic form.
//!
//! - A [`StructType`] descriptor is instantiated every time a `struct` form is evaluated;
//!   two separate evaluations never share a type descriptor, even if they specify the same name and fields.
//! - A [`Struct`] represents an instance. It is considered an instance of its direct type as well
//!   as of all ancestor supertypes in its hierarchy.
//!
//! # Equality and String Representation
//!
//! An instance is displayed with its fields using the format `#(struct:point 1 2)`.
//! Two instances compare `equal?` if they share the exact same [`StructType`] descriptor and all
//! corresponding fields compare `equal?`.
//!
//! Identity types are the exception: instances of an identity type compare `equal?` only under
//! identity (`eq?`). Any subtype of an identity type automatically inherits this identity-equality behavior.
//!
//! # Field Layout
//!
//! A struct type records the names of its fields—inherited supertype fields first, followed by its
//! own fields—along with [`FieldFlags`] for each field.
//!
//! - A field index is its 0-based offset in this combined field sequence. Code generated by
//!   `struct` expansions accesses fields by index.
//! - Attempting to mutate an immutable field raises a [`Fault::Immutable`] error regardless of context.
//!
//! # Struct Operations and Intrinsic Usage
//!
//! Struct construction, field reads, and field writes are normally performed through procedures generated
//! by a `struct` definition. The underlying primitive intrinsics are
//! [internal](crate::Intrinsic::is_internal).
//!
//! - A field read via `struct-ref` verifies that the target value is an instance of the expected struct type.
//! - If the compiler has already verified the type statically or dynamically (e.g., following `(point? p)`),
//!   it emits `struct-field`, which accesses the field without performing type checks.
//!
//! Introspection operations inspect structs immutably:
//! - `struct-type`: returns the [`StructType`] descriptor of an instance.
//! - `struct-fields`: returns a list of symbols representing a type's field names.
//! - `struct->list`: returns a list containing an instance's field values in declaration order.
//!
//! # Sealed Types
//!
//! A sealed type cannot be extended as a supertype; attempting to define a subtype of a sealed type
//! raises a fault.

use ragwort_types::bytevector::{AnyBytevector, Bytevectors};
use ragwort_types::gc::{Gc, Mutation, ScratchVec, Value};
use ragwort_types::pair::Pairs;
use ragwort_types::symbol::Symbol;
use ragwort_types::vector::{AnyVector, Vectors};

use crate::Fault;
use crate::objects::{Struct, StructFields, StructType, StructTypeFields};

bitflags::bitflags! {
    /// Configuration flags declared on a struct type by a `struct` form.
    #[derive(Clone, Copy, PartialEq, Eq, Debug)]
    pub struct TypeFlags: u32 {
        /// Indicates that instances compare `equal?` by pointer identity (`eq?`) only. Automatically inherited by subtypes.
        const IDENTITY = 1;
        /// Prevents the type from being used as a supertype; attempting to extend it raises an error.
        const SEALED = 1 << 1;
    }

    /// Configuration flags declared for an individual struct field.
    #[derive(Clone, Copy, PartialEq, Eq, Debug)]
    pub struct FieldFlags: u8 {
        /// Indicates that the field is mutable and can be modified after initialization.
        const MUTABLE = 1;
    }
}

/// Returns the [`TypeFlags`] declared on the struct type descriptor `kind`.
pub fn type_flags<'gc>(mc: &Mutation<'gc>, kind: Gc<'gc, StructType>) -> TypeFlags {
    TypeFlags::from_bits_truncate(kind.flags(mc))
}

/// Returns the [`FieldFlags`] for field index `k` of `kind`, or empty flags if index `k` is out of bounds.
pub fn field_flags<'gc>(mc: &Mutation<'gc>, kind: Gc<'gc, StructType>, k: usize) -> FieldFlags {
    flags_at(mc, kind.field_flags(mc), k)
}

/// Returns the [`FieldFlags`] at byte index `k` within a type's field flags bytevector.
fn flags_at<'gc>(mc: &Mutation<'gc>, bytes: Value<'gc>, k: usize) -> FieldFlags {
    FieldFlags::from_bits_truncate(AnyBytevector::of(bytes).and_then(|flags| flags.get(mc, k)).unwrap_or(0))
}

/// Builds the complete field layout for a struct type, returning a tuple containing an immutable vector
/// of field names, an immutable bytevector of field flags, and the total field count.
///
/// Inherited fields from `above` (if any) are placed first, followed by the direct fields specified by
/// `own` (a list of symbols) and their corresponding flags in `flags` (a list of fixnum bitmasks).
fn fields_of<'gc>(mc: &Mutation<'gc>, above: Option<Gc<'gc, StructType>>, own: Value<'gc>, flags: Value<'gc>) -> Result<(Value<'gc>, Value<'gc>, u32), Fault> {
    let pairs = Pairs::new(mc);
    if pairs.list_len(own).is_none() || pairs.list_len(own) != pairs.list_len(flags) {
        return Err(Fault::WrongType);
    }
    let (mut names, mut bits) = (ScratchVec::new(mc), ScratchVec::new(mc));
    if let Some(above) = above {
        let (above_names, above_bits) = (AnyVector::of(above.names(mc)).ok_or(Fault::Malformed)?, AnyBytevector::of(above.field_flags(mc)).ok_or(Fault::Malformed)?);
        for i in 0..above_names.len(mc) {
            names.push(above_names.get(mc, i).ok_or(Fault::Malformed)?)?;
            bits.push(above_bits.get(mc, i).ok_or(Fault::Malformed)?)?;
        }
    }
    for (name, flag) in pairs.elements(own).zip(pairs.elements(flags)) {
        Symbol::of(name).ok_or(Fault::WrongType)?;
        let flag = flag.as_fixnum().and_then(|bits| u8::try_from(bits).ok()).and_then(FieldFlags::from_bits).ok_or(Fault::WrongType)?;
        names.push(name)?;
        bits.push(flag.bits())?;
    }
    let count = u32::try_from(names.len()).map_err(|_| Fault::OutOfRange)?;
    Ok((Vectors::new(mc).immutable_from_slice(&names)?.value(mc), Bytevectors::new(mc).immutable_from_slice(&bits)?.value(mc), count))
}

/// Constructs and initializes a new struct type descriptor ([`StructType`]).
///
/// # Arguments
/// - `name`: A symbol representing the type name.
/// - `parent`: An unsealed struct type descriptor to inherit from, or `#f` for a base type.
/// - `fields`: A list of symbols specifying direct field names added by this type.
/// - `field_flags`: A list of fixnum bitmasks representing the [`FieldFlags`] for each direct field.
/// - `flags`: A fixnum bitmask representing the declared [`TypeFlags`]. Inherits `IDENTITY` if `parent` is an identity type.
pub fn make_type<'gc>(
    mc: &Mutation<'gc>,
    name: Value<'gc>,
    parent: Value<'gc>,
    fields: Value<'gc>,
    field_flags: Value<'gc>,
    flags: Value<'gc>,
) -> Result<Gc<'gc, StructType>, Fault> {
    Symbol::of(name).ok_or(Fault::WrongType)?;
    let mut flags = flags.as_fixnum().and_then(|bits| u32::try_from(bits).ok()).and_then(TypeFlags::from_bits).ok_or(Fault::WrongType)?;
    let parent = if parent == Value::FALSE { None } else { Some(type_of(mc, parent)?) };
    let above = parent.map_or(TypeFlags::empty(), |parent| type_flags(mc, parent));
    if above.contains(TypeFlags::SEALED) {
        return Err(Fault::WrongType);
    }
    flags |= above & TypeFlags::IDENTITY;
    let (names, field_flags, count) = fields_of(mc, parent, fields, field_flags)?;
    let made = |supertypes: usize, last: Value<'gc>| StructType::new(mc, name, names, field_flags, count, flags.bits(), supertypes, last);
    let Some(parent) = parent else { return Ok(made(0, Value::VOID)?) };
    let above = parent.items(mc);
    let kind = made(above.len() + 1, Value::object(mc, parent))?;
    let supertypes = kind.items(mc);
    (0..above.len()).for_each(|i| supertypes.set(mc, i, above.get(i)));
    Ok(kind)
}

/// Returns `true` if field index `k` of struct type `kind` is mutable.
pub fn is_mutable<'gc>(mc: &Mutation<'gc>, kind: Gc<'gc, StructType>, k: usize) -> bool {
    field_flags(mc, kind, k).contains(FieldFlags::MUTABLE)
}

/// Reads field index `k` from struct instance `s`, validating that `s` is an instance of `kind`
/// and that `k` is a valid field index for `kind` (implements runtime `struct-ref`).
#[inline]
pub fn field_of<'gc>(mc: &Mutation<'gc>, s: Value<'gc>, kind: Value<'gc>, k: usize) -> Result<Value<'gc>, Fault> {
    let kind = type_of(mc, kind)?;
    let fields = of(mc, s, kind).ok_or(Fault::WrongType)?.items(mc);
    // Any valid instance of `kind` has at least as many fields as defined by `kind`.
    if k >= kind.fields(mc) as usize {
        return Err(Fault::OutOfRange);
    }
    Ok(fields.get(k))
}

/// Accesses field index `k` from struct instance `s` without checking its struct type (implements runtime `struct-field`).
#[inline]
pub fn field<'gc>(mc: &Mutation<'gc>, s: Value<'gc>, k: usize) -> Result<Value<'gc>, Fault> {
    let fields = s.downcast::<Struct>(mc).ok_or(Fault::WrongType)?.items(mc);
    if k >= fields.len() {
        return Err(Fault::OutOfRange);
    }
    Ok(fields.get(k))
}

/// Downcasts `v` to a struct type descriptor (`Gc<StructType>`), returning `Fault::WrongType` if `v` is not one.
pub fn type_of<'gc>(mc: &Mutation<'gc>, v: Value<'gc>) -> Result<Gc<'gc, StructType>, Fault> {
    v.downcast::<StructType>(mc).ok_or(Fault::WrongType)
}

/// Instantiates a struct instance of type `kind`, initializing its fields from the `fields` iterator.
/// Returns `Fault::Arity` if the iterator length does not match `kind`'s total field count.
pub fn make<'gc>(mc: &Mutation<'gc>, kind: Gc<'gc, StructType>, fields: impl ExactSizeIterator<Item = Value<'gc>>) -> Result<Gc<'gc, Struct>, Fault> {
    if fields.len() != kind.fields(mc) as usize {
        return Err(Fault::Arity);
    }
    let made = Struct::new(mc, Some(kind), fields.len(), Value::VOID)?;
    let items = made.items(mc);
    fields.enumerate().for_each(|(i, field)| items.set(mc, i, field));
    Ok(made)
}

/// Returns `true` if struct type `kind` is identical to, or inherits from, struct type `from`.
#[inline]
pub fn derives<'gc>(mc: &Mutation<'gc>, kind: Gc<'gc, StructType>, from: Gc<'gc, StructType>) -> bool {
    if kind == from {
        return true;
    }
    // In the linear supertype array, an ancestor type at inheritance depth `depth` is stored at index `depth` in any subtype's supertype array.
    let (supertypes, depth) = (kind.items(mc), from.items(mc).len());
    depth < supertypes.len() && supertypes.get(depth) == Value::object(mc, from)
}

/// Downcasts `v` to a struct instance (`Gc<Struct>`) if `v` is an instance of `kind` or any of its subtypes; otherwise returns `None`.
#[inline]
pub fn of<'gc>(mc: &Mutation<'gc>, v: Value<'gc>, kind: Gc<'gc, StructType>) -> Option<Gc<'gc, Struct>> {
    let made = v.downcast::<Struct>(mc)?;
    derives(mc, made.kind(mc)?, kind).then_some(made)
}
